// @vitest-environment node
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "fs";
import { tmpdir } from "os";
import { join } from "path";
import { spawnSync, type SpawnSyncReturns } from "child_process";
import { load } from "js-yaml";
import { AppInfo } from "app-builder-lib/out/appInfo";
import FpmTarget from "app-builder-lib/out/targets/FpmTarget";
import type { Configuration } from "app-builder-lib/out/configuration";
import type { LinuxPackager } from "app-builder-lib/out/linuxPackager";
import type { LinuxTargetHelper } from "app-builder-lib/out/targets/LinuxTargetHelper";
import { afterEach, describe, expect, it } from "vitest";

const projectDir = join(import.meta.dirname, "..");
const config = load(
  readFileSync(join(projectDir, "electron-builder.yml"), "utf8"),
) as Configuration;
const metadata = JSON.parse(
  readFileSync(join(projectDir, "package.json"), "utf8"),
);
const homes: string[] = [];
// Real generated hooks spawn several native shell helpers. A five-second
// ceiling repeatedly expires on macOS during a four-worker suite, despite the
// unchanged fixture passing alone. Keep a hard process bound and time to assert
// its actual exit status; this does not change application or package behavior.
const HOOK_PROCESS_TIMEOUT_MS = 15_000;
afterEach(() => {
  for (const home of homes.splice(0))
    rmSync(home, { recursive: true, force: true });
});

async function runHook(
  name: "deb" | "rpm",
  options: {
    enabled?: boolean;
    compatible?: boolean;
    chroot?: boolean;
    loadFailure?: boolean;
    userns?: boolean;
  } = {},
): Promise<{
  result: SpawnSyncReturns<string>;
  commands: string;
  installed: string;
  profile: string;
  install: string;
}> {
  const home = mkdtempSync(join(tmpdir(), "hermes-package-hook-"));
  homes.push(home);
  const appInfo = new AppInfo(
    { config, metadata } as LinuxPackager["info"],
    undefined,
    config.linux,
  );
  const executableName = appInfo.sanitizedName.toLowerCase();
  let scriptNumber = 0;
  const packager = {
    config,
    appInfo,
    executableName,
    projectDir,
    platformSpecificBuildOptions: config.linux,
    info: {
      tempDirManager: {
        getTempFile: async ({ suffix }: { suffix: string }) =>
          join(home, `generated-${++scriptNumber}-${suffix}`),
      },
    },
  } as unknown as LinuxPackager;
  // Exercise the installed builder's actual template selection/interpolation;
  // no native package build, install, or root helper is invoked.
  const target = new FpmTarget(name, packager, {} as LinuxTargetHelper, home);
  const scripts = await (Reflect.get(target, "scriptFiles") as Promise<{
    afterInstall: string;
    appArmor: string;
  }>);
  const profile = readFileSync(scripts.appArmor, "utf8");
  const install = join(home, "installation");
  const policies = join(home, "apparmor.d");
  const bin = join(home, "bin");
  mkdirSync(join(install, "resources"), { recursive: true });
  mkdirSync(policies);
  mkdirSync(bin);
  writeFileSync(join(install, "resources/apparmor-profile"), profile);
  writeFileSync(join(install, "chrome-sandbox"), "harmless fixture");
  symlinkSync("/bin/sh", join(home, "user-namespace"));
  const commandLog = join(home, "commands.log");
  const header =
    '#!/bin/bash\nprintf "%s\\t%s\\n" "${0##*/}" "$*" >> "$FIXTURE_COMMAND_LOG"\n';
  const shim = (command: string, body: string): void =>
    writeFileSync(join(bin, command), header + body, { mode: 0o755 });
  for (const command of [
    "chmod",
    "update-alternatives",
    "update-mime-database",
    "update-desktop-database",
  ])
    shim(command, "exit 0\n");
  shim("unshare", `exit ${options.userns ? 0 : 1}\n`);
  shim("apparmor_status", `exit ${options.enabled === false ? 1 : 0}\n`);
  shim("ischroot", `exit ${options.chroot ? 0 : 1}\n`);
  shim(
    "apparmor_parser",
    `if [[ "$1" == "--skip-kernel-load" ]]; then exit ${options.compatible === false ? 1 : 0}; fi\nexit ${options.loadFailure ? 7 : 0}\n`,
  );
  // Redirect only the builder's fixed system paths into this temporary home.
  // cp remains real, so successful installation must copy the generated bytes.
  const script = readFileSync(scripts.afterInstall, "utf8")
    .replaceAll(`/opt/${appInfo.sanitizedProductName}`, install)
    .replaceAll(
      `/etc/apparmor.d/${executableName}`,
      join(policies, executableName),
    )
    .replaceAll(`/usr/bin/${executableName}`, join(home, executableName))
    .replaceAll("/etc/alternatives/", `${home}/alternatives/`)
    .replaceAll("/usr/share/", `${home}/share/`)
    .replaceAll("/usr/bin/ischroot", join(bin, "ischroot"))
    .replaceAll("/proc/self/ns/user", join(home, "user-namespace"));
  expect(script).not.toMatch(
    /\/opt\/HermesOne|\/etc\/apparmor\.d|\/usr\/bin\/ischroot/,
  );
  const hook = join(home, "safe-post-install.sh");
  writeFileSync(hook, script);
  const result = spawnSync("/bin/bash", [hook], {
    env: {
      ...process.env,
      PATH: `${bin}:/usr/bin:/bin`,
      FIXTURE_COMMAND_LOG: commandLog,
    },
    encoding: "utf8",
    timeout: HOOK_PROCESS_TIMEOUT_MS,
  });
  return {
    result,
    commands: existsSync(commandLog) ? readFileSync(commandLog, "utf8") : "",
    installed: join(policies, executableName),
    profile,
    install,
  };
}

// The generated hooks and harmless command shims require a POSIX shell.
// Cross-platform packaging assertions remain in packaging-identity.test.ts.
describe.skipIf(process.platform === "win32")(
  "POSIX Linux package hooks",
  { timeout: HOOK_PROCESS_TIMEOUT_MS + 5_000 },
  () => {
    // @lat: [[desktop-updates#Desktop Updates#Stable and beta release channels#Linux package sandbox and AppArmor#Compatible profile installation]]
    it.each(["deb", "rpm"] as const)(
      "installs and loads the actual generated %s profile",
      async (name) => {
        const fixture = await runHook(name);
        expect(fixture.result.status).toBe(0);
        expect(existsSync(fixture.installed)).toBe(true);
        expect(readFileSync(fixture.installed, "utf8")).toBe(fixture.profile);
        expect(fixture.profile).toContain('"/opt/HermesOne/hermes-desktop"');
        expect(fixture.commands).toContain(
          "apparmor_parser\t--skip-kernel-load --debug",
        );
        expect(fixture.commands).toContain(
          `apparmor_parser\t--replace --write-cache --skip-read-cache ${fixture.installed}`,
        );
      },
    );

    // @lat: [[desktop-updates#Desktop Updates#Stable and beta release channels#Linux package sandbox and AppArmor#Unsupported AppArmor]]
    it.each([{ enabled: false }, { compatible: false }])(
      "skips unavailable/unsupported AppArmor without loading it ($enabled/$compatible)",
      async (options) => {
        const fixture = await runHook("deb", options);
        expect(fixture.result.status).toBe(0);
        expect(existsSync(fixture.installed)).toBe(false);
        expect(fixture.commands).not.toContain("--replace");
        if (options.compatible === false)
          expect(fixture.result.stdout).toContain(
            "Skipping the installation of the AppArmor profile",
          );
      },
    );

    // @lat: [[desktop-updates#Desktop Updates#Stable and beta release channels#Linux package sandbox and AppArmor#Image-building chroot]]
    it("copies the compatible profile without loading host policy in a chroot", async () => {
      const fixture = await runHook("deb", { chroot: true });
      expect(fixture.result.status).toBe(0);
      expect(readFileSync(fixture.installed, "utf8")).toBe(fixture.profile);
      expect(fixture.commands).toContain("ischroot");
      expect(fixture.commands).not.toContain("--replace");
    });

    // @lat: [[desktop-updates#Desktop Updates#Stable and beta release channels#Linux package sandbox and AppArmor#Real load failures remain visible]]
    it("reports a supported profile's actual load failure instead of treating it as unsupported", async () => {
      const fixture = await runHook("deb", { loadFailure: true });
      expect(fixture.result.status).toBe(7);
      expect(existsSync(fixture.installed)).toBe(true);
      expect(fixture.commands).toContain("--replace");
    });

    // @lat: [[desktop-updates#Desktop Updates#Stable and beta release channels#Linux package sandbox and AppArmor#Conditional sandbox permission]]
    it.each([
      { userns: true, mode: "0755" },
      { userns: false, mode: "4755" },
    ])(
      "uses sandbox mode $mode when user namespaces are $userns",
      async ({ userns, mode }) => {
        const fixture = await runHook("rpm", { userns });
        expect(fixture.result.status).toBe(0);
        expect(fixture.commands).toContain(
          `chmod\t${mode} ${fixture.install}/chrome-sandbox`,
        );
      },
    );
  },
);
